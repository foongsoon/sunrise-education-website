// ==================== I18N FUNCTIONS ====================
class I18n {
    constructor() {
        this.currentLanguage = this.detectLanguage();
        this.init();
    }

    detectLanguage() {
        // Check localStorage first
        const stored = localStorage.getItem('preferredLanguage');
        if (stored && translations[stored]) {
            return stored;
        }

        // Check browser language
        const browserLang = navigator.language.split('-')[0];
        if (translations[browserLang]) {
            return browserLang;
        }

        // Default to English
        return 'en';
    }

    init() {
        this.applyLanguage(this.currentLanguage);
        this.setupLanguageToggle();
    }

    setLanguage(lang) {
        if (translations[lang]) {
            this.currentLanguage = lang;
            localStorage.setItem('preferredLanguage', lang);
            this.applyLanguage(lang);
            document.documentElement.lang = lang;
        }
    }

    applyLanguage(lang) {
        const trans = translations[lang];
        
        // Update all elements with data-i18n attribute
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (trans[key]) {
                el.textContent = trans[key];
            }
        });

        // Update placeholders
        document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
            const key = el.getAttribute('data-i18n-placeholder');
            if (trans[key]) {
                el.placeholder = trans[key];
            }
        });

        // Update document language
        document.documentElement.lang = lang;

        // Show language preference
        const indicator = document.getElementById('language-indicator');
        if (indicator) {
            const langNames = { en: 'English', zh: '中文', ms: 'Bahasa Melayu' };
            indicator.textContent = `Language: ${langNames[lang]}`;
        }
    }

    setupLanguageToggle() {
        const toggle = document.getElementById('language-toggle');
        const menu = document.getElementById('language-menu');
        const options = document.querySelectorAll('.lang-option');

        if (toggle) {
            toggle.addEventListener('click', () => {
                menu.classList.toggle('hidden');
            });
        }

        options.forEach(option => {
            option.addEventListener('click', () => {
                const lang = option.getAttribute('data-lang');
                this.setLanguage(lang);
                
                // Update toggle button
                const label = option.getAttribute('data-label');
                const langText = toggle.querySelector('.lang-text');
                if (langText) langText.textContent = label.split(' ')[0];
                
                menu.classList.add('hidden');
            });
        });

        // Close menu when clicking outside
        document.addEventListener('click', (e) => {
            if (!toggle.contains(e.target) && !menu.contains(e.target)) {
                menu.classList.add('hidden');
            }
        });
    }

    t(key) {
        return translations[this.currentLanguage]?.[key] || key;
    }
}

// Initialize on load
let i18n;
document.addEventListener('DOMContentLoaded', () => {
    i18n = new I18n();
});